/**
 * Returns a list of random Hindi words based on difficulty and options
 */
export function generateHindiWords(
  count: number = 50,
  difficulty: 'easy' | 'medium' | 'hard' = 'medium',
  includePunctuation: boolean = false,
  includeNumbers: boolean = false
): string[] {
  let pool: string[] = [];

  if (difficulty === 'easy') {
    pool = [...EASY_WORDS, ...CATEGORY_WORDS.dailyLife];
  } else if (difficulty === 'hard') {
    pool = [...HARD_WORDS, ...CATEGORY_WORDS.technology, ...CATEGORY_WORDS.maharashtra];
  } else {
    // medium (default)
    pool = [
      ...EASY_WORDS,
      ...MEDIUM_WORDS,
      ...CATEGORY_WORDS.india,
      ...CATEGORY_WORDS.education,
      ...CATEGORY_WORDS.dailyLife
    ];
  }

  // Shuffle pool using Fisher-Yates
  const shuffled = [...pool];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  const result: string[] = [];
  for (let i = 0; i < count; i++) {
    let word = shuffled[i % shuffled.length];

    if (includeNumbers && Math.random() < 0.15) {
      const num = Math.floor(Math.random() * 90 + 10).toString();
      word = Math.random() > 0.5 ? `${word}${num}` : num;
    }

    if (includePunctuation && Math.random() < 0.2) {
      const punc = HINDI_PUNCTUATION[Math.floor(Math.random() * HINDI_PUNCTUATION.length)];
      if (punc === '"' || punc === "'") {
        word = `${punc}${word}${punc}`;
      } else {
        word = `${word}${punc}`;
      }
    }

    result.push(word);
  }

  return result;
}

/**
 * Returns a random quote
 */
export function getRandomQuote(): HindiQuote {
  const index = Math.floor(Math.random() * HINDI_QUOTES.length);
  return HINDI_QUOTES[index];
}
